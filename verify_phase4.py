import pandas as pd
pd.set_option("display.width", 200)
base = "data/processed/daic"
m = pd.read_csv(base + "/manifest.csv")
print("has_audio False:", m.loc[~m["has_audio"].astype(bool), "session_id"].tolist())
print("has_transcript False:", m.loc[~m["has_transcript"].astype(bool), "session_id"].tolist())
print("test labels present:", int(m.loc[m["split"] == "test", "phq8_binary"].notna().sum()))
print("\nnotes (non-empty):")
print(m.loc[m["notes"].notna(), ["session_id", "split", "notes"]].to_string(index=False))
w = pd.read_parquet(base + "/windows.parquet")
print("\ntotal windows:", len(w))
print("sessions with windows:", w["session_id"].nunique())
print("max splits per session (must be 1):", w.groupby("session_id")["split"].nunique().max())
print("\nwindows per split and label (NaN = no label)")
print(w.groupby("split")["label"].value_counts(dropna=False).unstack(fill_value=0))
print("\nwindows per split and scale")
print(pd.crosstab(w["split"], w["scale"]))
print("\nduration by scale (seconds)")
print(w.groupby("scale")["duration"].describe().round(1))
print("\nempty text windows:", int((w["text"].fillna("").str.strip() == "").sum()))
bad = set(w["session_id"]) - set(m["session_id"])
print("window sessions not in manifest (must be 0):", len(bad))