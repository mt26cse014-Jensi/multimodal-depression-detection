"""
Script to describe all trainable model architectures across EATD and DAIC-WOZ.
Builds each model WITHOUT loading data or training, prints print(model) and
exact parameter counts, and writes output to docs/model_architectures.txt.
"""

from __future__ import annotations

import io
import os
import sys
from pathlib import Path
import torch
import torch.nn as nn

# Ensure project root is in sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.models.train_eatd_baselines import DepMLP
from src.models.train_daic import MultiTaskDepMLP
from src.models.cross_modal_attention import SmallCrossModalModel


def count_parameters(model: nn.Module) -> tuple[int, int]:
    """Return (trainable_params, total_params)."""
    trainable = sum(p.numel() for p in model.parameters() if p.requires_grad)
    total = sum(p.numel() for p in model.parameters())
    return trainable, total


def build_and_describe_all() -> str:
    out = io.StringIO()

    def p(text: str = "") -> None:
        print(text)
        out.write(text + "\n")

    p("=" * 80)
    p("TRAINABLE MODEL ARCHITECTURES: EATD-CORPUS AND DAIC-WOZ")
    p("Generated by scripts/describe_models.py")
    p("=" * 80)

    # ─────────────────────────────────────────────────────────────────────────
    # 1. EATD-Corpus Models (DepMLP)
    # ─────────────────────────────────────────────────────────────────────────
    p("\n" + "#" * 80)
    p("# PART 1: EATD-CORPUS MODELS (DepMLP: Binary Classification Head)")
    p("#" * 80)

    eatd_specs = [
        ("EATD Text-Only (Chinese-RoBERTa 768-d)", 768),
        ("EATD Audio-Only Primary (Wav2Vec2-XLS-R-300M 2048-d [1024 mean + 1024 std])", 2048),
        ("EATD Audio-Only Alt (WavLM-Base-Plus 1536-d [768 mean + 768 std])", 1536),
        ("EATD Multimodal Fusion Primary (Text 768 + XLS-R 2048 = 2816-d)", 2816),
        ("EATD Multimodal Fusion Alt (Text 768 + WavLM 1536 = 2304-d)", 2304),
    ]

    for title, in_dim in eatd_specs:
        model = DepMLP(input_dim=in_dim, hidden_dim=128, dropout=0.3)
        trainable, total = count_parameters(model)
        p("\n" + "-" * 70)
        p(f"MODEL: {title}")
        p(f"Input Dimension: {in_dim}")
        p(f"Trainable Parameters: {trainable:,} ({trainable})")
        p(f"Total Parameters:     {total:,} ({total})")
        p("Layer Breakdown:")
        for name, param in model.named_parameters():
            p(f"  - {name:20s}: shape {str(tuple(param.shape)):18s} -> {param.numel():,d} parameters")
        p("Architecture PyTorch Module:")
        p(str(model))

    # ─────────────────────────────────────────────────────────────────────────
    # 2. DAIC-WOZ Phase 5 Multi-Task Models (MultiTaskDepMLP)
    # ─────────────────────────────────────────────────────────────────────────
    p("\n" + "#" * 80)
    p("# PART 2: DAIC-WOZ PHASE 5 MULTI-TASK MODELS (MultiTaskDepMLP)")
    p("# Dual Head: Binary Logit (Linear(128, 1)) + PHQ-8 Regression (Linear(128, 1))")
    p("#" * 80)

    daic_specs = [
        ("DAIC-WOZ Text-Only (RoBERTa-base 768-d)", 768),
        ("DAIC-WOZ Audio-Only (WavLM-base-plus 1536-d [768 mean + 768 std])", 1536),
        ("DAIC-WOZ Late-Fusion (RoBERTa 768 + WavLM 1536 = 2304-d)", 2304),
    ]

    for title, in_dim in daic_specs:
        model = MultiTaskDepMLP(input_dim=in_dim, hidden_dim=128, dropout=0.3)
        trainable, total = count_parameters(model)
        p("\n" + "-" * 70)
        p(f"MODEL: {title}")
        p(f"Input Dimension: {in_dim}")
        p(f"Trainable Parameters: {trainable:,} ({trainable})")
        p(f"Total Parameters:     {total:,} ({total})")
        p("Layer Breakdown:")
        for name, param in model.named_parameters():
            p(f"  - {name:20s}: shape {str(tuple(param.shape)):18s} -> {param.numel():,d} parameters")
        p("Architecture PyTorch Module:")
        p(str(model))

    # ─────────────────────────────────────────────────────────────────────────
    # 3. DAIC-WOZ Phase 6 Cross-Modal Attention Models (SmallCrossModalModel)
    # ─────────────────────────────────────────────────────────────────────────
    p("\n" + "#" * 80)
    p("# PART 3: DAIC-WOZ PHASE 6 CROSS-MODAL ATTENTION MODELS (SmallCrossModalModel)")
    p("# Input: Text token seqs (768-d) + Audio frame seqs (768-d at 25 fps)")
    p("# Bidirectional CMA (T -> A and A -> T MHA) + Duration-Weighted Pooling + MLP Trunk + Heads")
    p("#" * 80)

    cma_specs = [
        ("DAIC-WOZ Cross-Modal Attention (1 Layer, 4 Heads)", 1),
        ("DAIC-WOZ Cross-Modal Attention (2 Layers, 4 Heads)", 2),
    ]

    for title, n_layers in cma_specs:
        model = SmallCrossModalModel(
            n_layers=n_layers,
            d_in_text=768,
            d_in_audio=768,
            d_model=128,
            n_heads=4,
            d_ff=256,
            hidden_dim=128,
            dropout=0.3,
            attn_dropout=0.1,
        )
        trainable, total = count_parameters(model)
        p("\n" + "-" * 70)
        p(f"MODEL: {title}")
        p(f"Number of CMA Layers: {n_layers}")
        p(f"Trainable Parameters: {trainable:,} ({trainable})")
        p(f"Total Parameters:     {total:,} ({total})")
        p("Layer Breakdown:")
        for name, param in model.named_parameters():
            p(f"  - {name:32s}: shape {str(tuple(param.shape)):18s} -> {param.numel():,d} parameters")
        p("Architecture PyTorch Module:")
        p(str(model))

    p("\n" + "=" * 80)
    p("END OF MODEL ARCHITECTURES SUMMARY")
    p("=" * 80)

    return out.getvalue()


def main() -> None:
    output_text = build_and_describe_all()
    out_dir = PROJECT_ROOT / "docs"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_file = out_dir / "model_architectures.txt"
    with open(out_file, "w", encoding="utf-8") as f:
        f.write(output_text)
    print(f"\nSuccessfully wrote model architecture summary to: {out_file}")


if __name__ == "__main__":
    main()

